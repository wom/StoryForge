# _build_video_prompt_request tests
# ---------------------------------------------------------------------------


class TestBuildVideoPromptRequest:
    """Test _build_video_prompt_request helper."""

    def test_basic_video_prompt_request(self):
        backend = DummyVideoBackend()
        result = backend._build_video_prompt_request("A test story.", "", 3)
        assert "3" in result
        assert "video" in result.lower()
        assert "A test story" in result
        assert "Camera" in result
        assert "Lighting" in result
        assert "Action" in result

    def test_video_prompt_includes_context(self):
        backend = DummyVideoBackend()
        result = backend._build_video_prompt_request("Story.", "Forest at night", 2)
        assert "Forest at night" in result
        assert "CONTEXT" in result

    def test_video_prompt_includes_character_descriptions(self):
        backend = DummyVideoBackend()
        result = backend._build_video_prompt_request(
            "Story.", "", 2, character_descriptions="Luna: golden hair, blue dress"
        )
        assert "Luna: golden hair, blue dress" in result
        assert "CHARACTER VISUAL DESCRIPTIONS" in result

    def test_video_prompt_scene_count(self):
        backend = DummyVideoBackend()
        result = backend._build_video_prompt_request("Story.", "", 5)
        assert "Scene 1:" in result
        assert "Scene 5:" in result


