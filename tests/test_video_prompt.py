class TestFormatVideoPromptFile:
    """Test format_video_prompt_file static method."""

    def test_format_with_story_prompt(self):
        prompts = ["Scene one description.", "Scene two description."]
        result = LLMBackend.format_video_prompt_file(prompts, "A brave cat")
        assert "Video Prompt — A brave cat" in result
        assert "Generated by StoryForge" in result
        assert "SCENE 1:" in result
        assert "SCENE 2:" in result
        assert "Scene one description." in result
        assert "Scene two description." in result

    def test_format_without_story_prompt(self):
        prompts = ["Only scene."]
        result = LLMBackend.format_video_prompt_file(prompts)
        assert result.startswith("Video Prompt\n")
        assert "SCENE 1:" in result

    def test_format_scene_labels(self):
        prompts = ["A", "B", "C"]
        result = LLMBackend.format_video_prompt_file(prompts)
        assert "Opening" in result
        assert "Climactic" in result or "closing" in result.lower()


